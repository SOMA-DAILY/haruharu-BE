BEGIN;
CREATE TABLE IF NOT EXISTS app_update_policy (
    id bigint PRIMARY KEY CHECK (id = 1),
    ios_minimum_version varchar(20),
    android_minimum_version varchar(20),
    revision bigint NOT NULL DEFAULT 0 CHECK (revision >= 0),
    updated_by bigint,
    updated_at timestamp(6)
);
CREATE TABLE IF NOT EXISTS app_update_policy_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    revision bigint NOT NULL,
    previous_ios_minimum_version varchar(20),
    previous_android_minimum_version varchar(20),
    ios_minimum_version varchar(20),
    android_minimum_version varchar(20),
    changed_by bigint NOT NULL,
    changed_at timestamp(6) NOT NULL,
    CONSTRAINT uq_app_update_policy_history_revision UNIQUE (revision)
);
INSERT INTO app_update_policy (id, revision) VALUES (1, 0) ON CONFLICT (id) DO NOTHING;
COMMIT;
