CREATE TABLE IF NOT EXISTS anonymous_questions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id BIGINT NOT NULL,
    sender_member_id BIGINT NOT NULL,
    recipient_member_id BIGINT NOT NULL,
    sender_user_id BIGINT NOT NULL,
    recipient_user_id BIGINT NOT NULL,
    recipient_nickname VARCHAR(30) NOT NULL,
    content VARCHAR(100) NOT NULL,
    request_id UUID NOT NULL,
    answer VARCHAR(200),
    answered_at TIMESTAMP,
    recipient_read BOOLEAN NOT NULL DEFAULT FALSE,
    sender_read BOOLEAN NOT NULL DEFAULT TRUE,
    sender_reported BOOLEAN NOT NULL DEFAULT FALSE,
    recipient_reported BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    deleted_at TIMESTAMP,
    CONSTRAINT uq_question_sender_target UNIQUE (room_id, sender_user_id, recipient_user_id),
    CONSTRAINT uq_question_request UNIQUE (room_id, sender_user_id, request_id),
    CONSTRAINT ck_question_content_length CHECK (char_length(content) BETWEEN 1 AND 50),
    CONSTRAINT ck_question_answer_length CHECK (answer IS NULL OR char_length(answer) BETWEEN 1 AND 100),
    CONSTRAINT ck_question_different_users CHECK (sender_user_id <> recipient_user_id)
);
ALTER TABLE anonymous_questions DROP CONSTRAINT IF EXISTS uq_question_sender_target;
ALTER TABLE anonymous_questions ADD CONSTRAINT uq_question_sender_target UNIQUE (room_id, sender_user_id, recipient_user_id);

-- Also install validation on a development database whose tables were created by Hibernate.
ALTER TABLE anonymous_questions DROP CONSTRAINT IF EXISTS ck_question_content_length;
ALTER TABLE anonymous_questions ADD CONSTRAINT ck_question_content_length CHECK (char_length(content) BETWEEN 1 AND 50);
ALTER TABLE anonymous_questions DROP CONSTRAINT IF EXISTS ck_question_answer_length;
ALTER TABLE anonymous_questions ADD CONSTRAINT ck_question_answer_length CHECK (answer IS NULL OR char_length(answer) BETWEEN 1 AND 100);
ALTER TABLE anonymous_questions DROP CONSTRAINT IF EXISTS ck_question_different_users;
ALTER TABLE anonymous_questions ADD CONSTRAINT ck_question_different_users CHECK (sender_user_id <> recipient_user_id);
CREATE INDEX IF NOT EXISTS idx_question_recipient ON anonymous_questions(room_id, recipient_user_id, id);

CREATE TABLE IF NOT EXISTS question_grants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    deleted_at TIMESTAMP,
    CONSTRAINT uq_question_grant UNIQUE (room_id, user_id)
);

-- Keep content reports independent of generic user reports. A generic duplicate-report response
-- must never reveal whether that user authored an anonymous question.
ALTER TABLE reports ADD COLUMN IF NOT EXISTS question_id BIGINT;
ALTER TABLE reports ADD COLUMN IF NOT EXISTS report_scope VARCHAR(40) NOT NULL DEFAULT 'USER';
UPDATE reports SET report_scope = CASE WHEN question_id IS NULL THEN 'USER' ELSE 'QUESTION:' || question_id END
WHERE report_scope IS DISTINCT FROM CASE WHEN question_id IS NULL THEN 'USER' ELSE 'QUESTION:' || question_id END;
ALTER TABLE reports ALTER COLUMN report_scope SET NOT NULL;
ALTER TABLE reports DROP CONSTRAINT IF EXISTS uq_reports_reporter_reported;
ALTER TABLE reports ADD CONSTRAINT uq_reports_reporter_reported
    UNIQUE (reporter_user_id, reported_user_id, report_scope);
CREATE INDEX IF NOT EXISTS idx_reports_question ON reports(question_id) WHERE question_id IS NOT NULL;

-- Hibernate does not widen an existing enum CHECK when an enum gains constants.
-- Preserve the existing expression and add only the three new values, including custom names.
DO $$
DECLARE existing RECORD;
BEGIN
    FOR existing IN
        SELECT conname, pg_get_expr(conbin, conrelid) AS expression
        FROM pg_constraint
        WHERE conrelid = 'notification_history'::regclass AND contype = 'c'
          AND conkey = ARRAY[(SELECT attnum FROM pg_attribute
                              WHERE attrelid = 'notification_history'::regclass AND attname = 'type')]
          AND pg_get_constraintdef(oid) ~ '\mtype\M'
          AND pg_get_constraintdef(oid) NOT LIKE '%QUESTION_ANSWERED%'
    LOOP
        EXECUTE format('ALTER TABLE notification_history DROP CONSTRAINT %I', existing.conname);
        EXECUTE format('ALTER TABLE notification_history ADD CONSTRAINT %I CHECK ((%s) OR type IN (''QUESTION_AVAILABLE'', ''QUESTION_RECEIVED'', ''QUESTION_ANSWERED''))',
            existing.conname, existing.expression);
    END LOOP;
END $$;

COMMIT;
