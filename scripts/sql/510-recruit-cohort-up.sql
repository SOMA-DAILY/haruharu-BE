-- #510: 모집 트랙(recruit_tracks)·기수(cohorts). app/admin 배포 전에 적용한다.
-- 재실행해도 안전하다. 새 버전을 먼저 띄워 ddl-auto 가 테이블을 만들었어도, 다시 돌리면 빠진 제약과 부분 유니크만 채운다.
-- 트랙당 OPEN 기수 1개(ux_cohorts_track_open)는 JPA 로 표현할 수 없어 이 스크립트에만 있다.
-- 칸 타입은 Hibernate 가 만드는 것과 같다(soft-delete 의 deleted_at 은 timestamptz).
BEGIN;
CREATE TABLE IF NOT EXISTS recruit_tracks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    track_key VARCHAR(40) NOT NULL,
    label VARCHAR(40) NOT NULL,
    region VARCHAR(40) NOT NULL,
    audience VARCHAR(20) NOT NULL,
    min_age INTEGER NOT NULL,
    max_age INTEGER NOT NULL,
    questions JSONB NOT NULL DEFAULT '[]'::jsonb,
    display_order INTEGER NOT NULL,
    active BOOLEAN NOT NULL,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    deleted_at TIMESTAMP(6) WITH TIME ZONE
);

CREATE TABLE IF NOT EXISTS cohorts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    track_id BIGINT NOT NULL,
    sequence INTEGER NOT NULL,
    status VARCHAR(20) NOT NULL,
    apply_opens_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    apply_closes_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    assign_deadline_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    period_label VARCHAR(40) NOT NULL,
    target_male INTEGER,
    target_female INTEGER,
    settled_at TIMESTAMP(6) WITHOUT TIME ZONE,
    created_by VARCHAR(40),
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    deleted_at TIMESTAMP(6) WITH TIME ZONE
);

-- ddl-auto 가 먼저 테이블을 만들었으면 Hibernate 가 enum 칸에 이름 없는 CHECK 를 붙인다(예: cohorts_status_check).
-- 값을 늘릴 때 두 곳을 고쳐야 하므로 걷어내고 아래 ck_* 하나만 남긴다.
DO $$
DECLARE r record;
BEGIN
    FOR r IN SELECT con.conrelid::regclass AS tbl, con.conname FROM pg_constraint con
             JOIN pg_attribute att ON att.attrelid = con.conrelid AND att.attnum = ANY (con.conkey)
             WHERE con.contype = 'c' AND con.conname NOT LIKE 'ck\_%'
               AND ((con.conrelid = 'cohorts'::regclass AND att.attname = 'status')
                 OR (con.conrelid = 'recruit_tracks'::regclass AND att.attname = 'audience')) LOOP
        EXECUTE format('ALTER TABLE %s DROP CONSTRAINT %I', r.tbl, r.conname);
    END LOOP;
END $$;

-- 제약은 이름으로 있는지 보고 없을 때만 건다(ddl-auto 가 먼저 만든 테이블에도 같은 이름으로 맞춘다).
DO $$
DECLARE c record;
BEGIN
    FOR c IN SELECT * FROM (VALUES
        ('recruit_tracks', 'uq_recruit_tracks_key', 'UNIQUE (track_key)'),
        ('recruit_tracks', 'ck_recruit_tracks_age', 'CHECK (min_age >= 19 AND min_age <= max_age AND max_age <= 100)'),
        ('recruit_tracks', 'ck_recruit_tracks_audience', 'CHECK (audience IN (''STUDENT'', ''WORKER''))'),
        ('recruit_tracks', 'ck_recruit_tracks_questions', 'CHECK (jsonb_typeof(questions) = ''array'')'),
        ('cohorts', 'fk_cohorts_track', 'FOREIGN KEY (track_id) REFERENCES recruit_tracks (id)'),
        ('cohorts', 'uq_cohorts_track_sequence', 'UNIQUE (track_id, sequence)'),
        ('cohorts', 'ck_cohorts_sequence', 'CHECK (sequence >= 1)'),
        ('cohorts', 'ck_cohorts_status', 'CHECK (status IN (''DRAFT'', ''OPEN'', ''SETTLED'', ''CANCELLED''))'),
        ('cohorts', 'ck_cohorts_apply_window', 'CHECK (apply_opens_at < apply_closes_at)'),
        ('cohorts', 'ck_cohorts_assign_deadline', 'CHECK (assign_deadline_at >= apply_closes_at)'),
        ('cohorts', 'ck_cohorts_targets', 'CHECK ((target_male IS NULL OR target_male >= 0) AND (target_female IS NULL OR target_female >= 0))')
    ) AS t(tbl, name, def) LOOP
        IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = c.tbl::regclass AND conname = c.name) THEN
            EXECUTE format('ALTER TABLE %I ADD CONSTRAINT %I %s', c.tbl, c.name, c.def);
        END IF;
    END LOOP;
END $$;

-- 트랙당 OPEN 기수 1개. 앱은 트랙 행 잠금으로 먼저 거르고, 이 인덱스가 최종으로 막는다.
CREATE UNIQUE INDEX IF NOT EXISTS ux_cohorts_track_open ON cohorts (track_id) WHERE status = 'OPEN' AND deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_cohorts_status ON cohorts (status);
COMMIT;
