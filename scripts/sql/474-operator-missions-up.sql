BEGIN;
CREATE TABLE IF NOT EXISTS operator_missions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id BIGINT NOT NULL,
    template_id VARCHAR(20) NOT NULL,
    content VARCHAR(500) NOT NULL,
    notify_participants BOOLEAN NOT NULL,
    scheduled_at TIMESTAMP(6) NOT NULL,
    immediate BOOLEAN NOT NULL,
    status VARCHAR(20) NOT NULL CHECK (status IN ('SCHEDULED', 'SENDING', 'SENT', 'FAILED', 'CANCELLED')),
    created_by BIGINT NOT NULL,
    request_key VARCHAR(80) NOT NULL,
    image_id BIGINT,
    message_id BIGINT,
    sent_at TIMESTAMP(6),
    fail_reason VARCHAR(200),
    delete_requested_at TIMESTAMP(6),
    delete_processed_at TIMESTAMP(6),
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    deleted_at TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT uq_operator_mission_request UNIQUE (room_id, request_key)
);
CREATE INDEX IF NOT EXISTS idx_operator_mission_due ON operator_missions (status, scheduled_at);
CREATE INDEX IF NOT EXISTS idx_operator_mission_history ON operator_missions (room_id, id);
ALTER TABLE chat_messages ADD COLUMN IF NOT EXISTS operator_mission_id BIGINT;
ALTER TABLE chat_messages ADD COLUMN IF NOT EXISTS mission_room_id BIGINT;
ALTER TABLE chat_messages ADD COLUMN IF NOT EXISTS mission_template_id VARCHAR(20);
ALTER TABLE chat_messages ADD COLUMN IF NOT EXISTS mission_title VARCHAR(40);
ALTER TABLE chat_messages ADD COLUMN IF NOT EXISTS admin_deleted BOOLEAN NOT NULL DEFAULT false;
CREATE UNIQUE INDEX IF NOT EXISTS uq_chat_message_operator_mission ON chat_messages (operator_mission_id);
CREATE TABLE IF NOT EXISTS operator_mission_images (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id BIGINT NOT NULL, created_by BIGINT NOT NULL, object_key VARCHAR(300) NOT NULL UNIQUE,
    width INTEGER NOT NULL CHECK (width > 0), height INTEGER NOT NULL CHECK (height > 0),
    created_at TIMESTAMP(6) NOT NULL, updated_at TIMESTAMP(6) NOT NULL, deleted_at TIMESTAMP(6) WITH TIME ZONE
);
ALTER TABLE operator_missions ADD COLUMN IF NOT EXISTS image_id BIGINT;
ALTER TABLE chat_messages ADD COLUMN IF NOT EXISTS mission_image_id BIGINT;
COMMIT;
