BEGIN;

-- 방별 미션 사용 여부(#449). 방당 1행. rooms 와 물리 FK 없음(도메인 분리 — room_id 논리 참조).
-- 적용 절차: ① 앱 배포 전에 1회 적용 ② 배포 완료 직후 1회 재실행.
-- 설정 행이 없는 방은 미션 꺼짐으로 판정된다. 백필 뒤 새 버전이 뜨기 전까지 이전 버전 서버가 만든 방은
-- 슬롯만 있고 설정 행이 없으므로, ② 재실행으로 그 방들을 채운다(ON CONFLICT 로 재실행 안전).
CREATE TABLE IF NOT EXISTS room_mission_settings (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    room_id         BIGINT NOT NULL,
    mission_enabled BOOLEAN NOT NULL,
    created_at      TIMESTAMP(6) NOT NULL,
    updated_at      TIMESTAMP(6) NOT NULL,
    deleted_at      TIMESTAMP(6) WITH TIME ZONE,
    PRIMARY KEY (id),
    CONSTRAINT uq_room_mission_settings_room UNIQUE (room_id)
);

COMMENT ON COLUMN room_mission_settings.deleted_at IS 'Soft-delete indicator';

-- 백필: 기존 방은 살아 있는 미션 슬롯이 있으면 켜짐, 없으면 꺼짐.
-- 이미 설정 행이 있는 방은 건드리지 않는다(재실행 안전).
INSERT INTO room_mission_settings (room_id, mission_enabled, created_at, updated_at)
SELECT r.id,
       EXISTS (SELECT 1 FROM room_mission_slots s WHERE s.room_id = r.id AND s.deleted_at IS NULL),
       CURRENT_TIMESTAMP,
       CURRENT_TIMESTAMP
FROM rooms r
ON CONFLICT (room_id) DO NOTHING;

COMMIT;
