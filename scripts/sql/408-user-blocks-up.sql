BEGIN;

-- 사용자 차단(#408). 차단자·대상 쌍당 1행. FK 물리 제약 없음(도메인 분리 설계 — 앱 레벨 논리 참조).
-- 해제는 앱이 native 물리 삭제로 수행한다(soft-delete 잔행이 UNIQUE 와 충돌해 재차단을 막지 않게).
CREATE TABLE IF NOT EXISTS user_blocks (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    blocker_user_id BIGINT NOT NULL,
    blocked_user_id BIGINT NOT NULL,
    created_at      TIMESTAMP(6) NOT NULL,
    updated_at      TIMESTAMP(6) NOT NULL,
    deleted_at      TIMESTAMP(6) WITH TIME ZONE,
    PRIMARY KEY (id),
    CONSTRAINT uq_user_blocks_blocker_blocked UNIQUE (blocker_user_id, blocked_user_id)
);

COMMENT ON COLUMN user_blocks.deleted_at IS 'Soft-delete indicator';

-- 목록 필터(내가 차단한 대상)·알림 필터(나를 차단한 유저) 양방향 조회용
CREATE INDEX IF NOT EXISTS idx_user_blocks_blocker ON user_blocks (blocker_user_id);
CREATE INDEX IF NOT EXISTS idx_user_blocks_blocked ON user_blocks (blocked_user_id);

COMMIT;
