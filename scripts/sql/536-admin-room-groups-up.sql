CREATE TABLE IF NOT EXISTS admin_room_groups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL,
    CONSTRAINT uk_admin_room_group_name UNIQUE (name),
    CONSTRAINT ck_admin_room_group_name CHECK (length(trim(name)) > 0)
);
CREATE TABLE IF NOT EXISTS admin_room_organizations (
    room_id BIGINT PRIMARY KEY REFERENCES rooms(id),
    group_id BIGINT REFERENCES admin_room_groups(id),
    is_test BOOLEAN
);
CREATE INDEX IF NOT EXISTS idx_admin_room_org_group_type ON admin_room_organizations(group_id,is_test);
