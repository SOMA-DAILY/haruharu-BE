CREATE TABLE room_mission_instances (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id bigint NOT NULL REFERENCES rooms(id),
    type varchar(30) NOT NULL CHECK (type IN ('ANNOUNCEMENT','PROFILE_REVEAL')),
    -- Type-specific definition. The type column decides how the object is read; no per-type table.
    details jsonb NOT NULL,
    opens_at timestamp(6) NOT NULL, closes_at timestamp(6), canceled_at timestamp(6),
    created_by varchar(40), updated_by varchar(40),
    created_at timestamp(6) NOT NULL, updated_at timestamp(6) NOT NULL, deleted_at timestamp(6) WITH TIME ZONE,
    CONSTRAINT uq_room_mission_instances_id_room UNIQUE (id,room_id),
    CONSTRAINT ck_room_mission_instances_details CHECK (jsonb_typeof(details)='object'),
    CONSTRAINT ck_room_mission_instances_window CHECK (closes_at IS NULL OR closes_at > opens_at)
);
CREATE INDEX idx_room_mission_instances_room_open ON room_mission_instances(room_id,opens_at,id);
CREATE TABLE mission_announcements (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_mission_id bigint NOT NULL, room_id bigint NOT NULL,
    announcement_type varchar(20) NOT NULL CHECK (announcement_type IN ('START','REMINDER','RESULT')),
    run_at timestamp(6) NOT NULL, content varchar(500), push boolean NOT NULL,
    push_title varchar(15), push_body varchar(30),
    status varchar(20) NOT NULL CHECK (status IN ('SCHEDULED','SENDING','SENT','CANCELED','FAILED')),
    fail_reason varchar(200), sent_message_id bigint REFERENCES chat_messages(id),
    legacy_schedule_item_id bigint,
    created_by varchar(40), updated_by varchar(40), sent_at timestamp(6),
    created_at timestamp(6) NOT NULL, updated_at timestamp(6) NOT NULL, deleted_at timestamp(6) WITH TIME ZONE,
    CONSTRAINT uq_mission_announcements_legacy UNIQUE (legacy_schedule_item_id),
    CONSTRAINT uq_mission_announcements_id_mission UNIQUE (id,room_mission_id),
    CONSTRAINT fk_mission_announcement_room FOREIGN KEY (room_mission_id,room_id) REFERENCES room_mission_instances(id,room_id)
);
CREATE INDEX idx_mission_announcements_due ON mission_announcements(status,run_at);
CREATE INDEX idx_mission_announcements_room ON mission_announcements(room_id,run_at);
CREATE INDEX idx_mission_announcements_mission ON mission_announcements(room_mission_id,run_at);
