-- #511: 기수 신청(cohort_applications)·참가권 사용 반환(ticket_ledger USE_REFUND)·프로필 번호(user_profiles.phone).
-- 510-recruit-cohort-up.sql 다음, app/admin 배포 전에 적용한다.
-- 재실행해도 안전하다. 새 버전을 먼저 띄워 ddl-auto 가 테이블·칸을 만들었어도, 다시 돌리면 빠진 제약과 부분 유니크만 채운다.
-- 다음 둘은 JPA 로 표현할 수 없어 이 스크립트에만 있다.
--   ux_cohort_applications_user_active      진행 중 신청 사람당 1건
--   ux_ticket_ledger_cohort_application_ref 같은 신청으로 참가권 사용·반환은 각 1번
-- 칸 타입은 Hibernate 가 만드는 것과 같다(soft-delete 의 deleted_at 은 timestamptz).
BEGIN;
DO $$
BEGIN
    IF to_regclass('cohorts') IS NULL OR to_regclass('recruit_tracks') IS NULL THEN
        RAISE EXCEPTION 'cohorts/recruit_tracks do not exist: apply 510-recruit-cohort-up.sql first';
    END IF;
    IF to_regclass('ticket_ledger') IS NULL OR to_regclass('user_profiles') IS NULL THEN
        RAISE EXCEPTION 'ticket_ledger/user_profiles do not exist';
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS cohort_applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    cohort_id BIGINT NOT NULL,
    track_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL,
    declared_gender VARCHAR(10),
    gender VARCHAR(20),
    birthday DATE,
    school VARCHAR(40) NOT NULL,
    department VARCHAR(15) NOT NULL,
    answers JSONB NOT NULL DEFAULT '{}'::jsonb,
    referral_source VARCHAR(40),
    friend_preference VARCHAR(20),
    motivation VARCHAR(300),
    survey_submitted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    priority INTEGER NOT NULL,
    applied_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    queued_at TIMESTAMP(6) WITHOUT TIME ZONE,
    review_reason VARCHAR(30),
    room_id BIGINT,
    assigned_at TIMESTAMP(6) WITHOUT TIME ZONE,
    assigned_by VARCHAR(40),
    closed_at TIMESTAMP(6) WITHOUT TIME ZONE,
    close_reason VARCHAR(30),
    refunded_at TIMESTAMP(6) WITHOUT TIME ZONE,
    admin_memo VARCHAR(500),
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    deleted_at TIMESTAMP(6) WITH TIME ZONE
);

-- ddl-auto 가 먼저 테이블을 만들었으면 Hibernate 가 enum 칸에 이름 없는 CHECK 를 붙인다(예: cohort_applications_status_check).
-- 값을 늘릴 때 두 곳을 고쳐야 하므로 걷어내고 아래 ck_* 하나만 남긴다.
DO $$
DECLARE r record;
BEGIN
    FOR r IN SELECT DISTINCT con.conname FROM pg_constraint con
             JOIN pg_attribute att ON att.attrelid = con.conrelid AND att.attnum = ANY (con.conkey)
             WHERE con.conrelid = 'cohort_applications'::regclass AND con.contype = 'c'
               AND con.conname NOT LIKE 'ck\_%'
               AND att.attname IN ('status', 'declared_gender', 'friend_preference', 'review_reason', 'close_reason') LOOP
        EXECUTE format('ALTER TABLE cohort_applications DROP CONSTRAINT %I', r.conname);
    END LOOP;
END $$;

-- 제약은 이름으로 있는지 보고 없을 때만 건다(ddl-auto 가 먼저 만든 테이블에도 같은 이름으로 맞춘다).
DO $$
DECLARE c record;
BEGIN
    FOR c IN SELECT * FROM (VALUES
        ('fk_cohort_applications_cohort', 'FOREIGN KEY (cohort_id) REFERENCES cohorts (id)'),
        ('fk_cohort_applications_track', 'FOREIGN KEY (track_id) REFERENCES recruit_tracks (id)'),
        ('ck_cohort_applications_status', 'CHECK (status IN (''IDENTITY_PENDING'', ''NEEDS_REVIEW'', ''QUEUED'', ''ASSIGNED'', ''COMPLETED'', ''CANCELLED'', ''NOT_ASSIGNED''))'),
        ('ck_cohort_applications_declared_gender', 'CHECK (declared_gender IN (''MALE'', ''FEMALE''))'),
        ('ck_cohort_applications_friend_preference', 'CHECK (friend_preference IN (''ALONE'', ''SAME_ROOM'', ''DIFFERENT_ROOM'', ''ANY''))'),
        ('ck_cohort_applications_review_reason', 'CHECK (review_reason IN (''UNKNOWN_GENDER'', ''GENDER_MISMATCH'', ''AGE_OUT_OF_RANGE''))'),
        ('ck_cohort_applications_close_reason', 'CHECK (close_reason IN (''USER_CANCELLED'', ''COHORT_CANCELLED'', ''DEADLINE_PASSED'', ''OPERATOR_EXCLUDED'', ''ROOM_CANCELLED'', ''ROOM_ENDED''))'),
        ('ck_cohort_applications_priority', 'CHECK (priority >= 0)'),
        ('ck_cohort_applications_answers', 'CHECK (jsonb_typeof(answers) = ''object'')'),
        -- 닫힌 상태와 닫힌 시각은 함께 다닌다.
        ('ck_cohort_applications_closed', 'CHECK ((status IN (''COMPLETED'', ''CANCELLED'', ''NOT_ASSIGNED'')) = (closed_at IS NOT NULL))')
    ) AS t(name, def) LOOP
        IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'cohort_applications'::regclass AND conname = c.name) THEN
            EXECUTE format('ALTER TABLE cohort_applications ADD CONSTRAINT %I %s', c.name, c.def);
        END IF;
    END LOOP;
END $$;

-- 진행 중 신청 사람당 1건. 앱은 지갑 행 잠금으로 먼저 거르고, 이 인덱스가 최종으로 막는다.
CREATE UNIQUE INDEX IF NOT EXISTS ux_cohort_applications_user_active ON cohort_applications (user_id)
    WHERE status IN ('IDENTITY_PENDING', 'NEEDS_REVIEW', 'QUEUED', 'ASSIGNED') AND deleted_at IS NULL;
-- 운영진 편성 풀: 기수·상태로 거르고 우선순위 높은 순, 먼저 대기한 순.
CREATE INDEX IF NOT EXISTS idx_cohort_applications_pool ON cohort_applications (cohort_id, status, priority DESC, queued_at);
CREATE INDEX IF NOT EXISTS idx_cohort_applications_user ON cohort_applications (user_id);

-- 원장 사유에 USE_REFUND(사용 반환)를 더한다. Hibernate 가 붙인 CHECK 까지 reason 칸의 CHECK 를 모두 걷고 하나로 다시 건다.
-- 다시 검증하는 동안 ticket_ledger 에 배타 잠금이 걸린다(행이 적어 짧다).
DO $$
DECLARE r record;
BEGIN
    -- 정의문 글자가 아니라 reason 칸에 걸린 CHECK 만 고른다(다른 칸의 CHECK 를 잘못 지우지 않게).
    FOR r IN SELECT DISTINCT con.conname FROM pg_constraint con
             JOIN pg_attribute att ON att.attrelid = con.conrelid AND att.attnum = ANY (con.conkey)
             WHERE con.conrelid = 'ticket_ledger'::regclass AND con.contype = 'c' AND att.attname = 'reason' LOOP
        EXECUTE format('ALTER TABLE ticket_ledger DROP CONSTRAINT %I', r.conname);
    END LOOP;
END $$;
ALTER TABLE ticket_ledger ADD CONSTRAINT ticket_ledger_reason_check
    CHECK (reason IN ('PURCHASE', 'USE', 'REFUND_REVOKE', 'ADMIN_GRANT', 'USE_REFUND'));

-- 같은 신청으로 참가권 사용(USE)·반환(USE_REFUND)은 각각 한 번. 조건부 전이가 먼저 막고, 이 인덱스가 최종으로 막는다.
CREATE UNIQUE INDEX IF NOT EXISTS ux_ticket_ledger_cohort_application_ref ON ticket_ledger (ref_type, ref_id, reason)
    WHERE ref_type = 'COHORT_APPLICATION';

ALTER TABLE user_profiles ADD COLUMN IF NOT EXISTS phone VARCHAR(20);
COMMIT;
