-- 방 편성(#457, F3/F4). 운영 글 예약과 프로필 항목 공개 시각. 시각 제한 없음(방 시작 전·종료 후·같은 항목 여러 행 허용).
CREATE TABLE IF NOT EXISTS room_schedule_items (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    room_id         BIGINT NOT NULL,
    run_at          TIMESTAMP(6) NOT NULL,
    reveal_fields   VARCHAR(60),
    message_content VARCHAR(500),
    push            BOOLEAN NOT NULL DEFAULT false,
    push_title      VARCHAR(15),
    push_body       VARCHAR(30),
    status          VARCHAR(20) NOT NULL,
    fail_reason     VARCHAR(200),
    sent_message_id BIGINT,
    created_by      VARCHAR(40),
    updated_by      VARCHAR(40),
    sent_at         TIMESTAMP(6),
    created_at      TIMESTAMP(6) NOT NULL,
    updated_at      TIMESTAMP(6) NOT NULL,
    deleted_at      TIMESTAMP(6) WITH TIME ZONE,
    PRIMARY KEY (id),
    CONSTRAINT room_schedule_items_status_check CHECK (status IN ('SCHEDULED', 'SENDING', 'SENT', 'CANCELED', 'FAILED')),
    CONSTRAINT room_schedule_items_content_check CHECK (reveal_fields IS NOT NULL OR message_content IS NOT NULL)
);
CREATE INDEX IF NOT EXISTS idx_room_schedule_items_status_run_at ON room_schedule_items (status, run_at);
CREATE INDEX IF NOT EXISTS idx_room_schedule_items_room_run_at ON room_schedule_items (room_id, run_at);
-- 운영 글(#457). 기존 행은 전부 TEXT. 운영자 삭제는 전역 @SoftDelete(deleted_at) 대신 admin_deleted_at('삭제된 메시지'로 내려야 해서).
ALTER TABLE chat_messages ADD COLUMN IF NOT EXISTS message_type varchar(20) NOT NULL DEFAULT 'TEXT';
ALTER TABLE chat_messages ADD COLUMN IF NOT EXISTS schedule_item_id bigint;
ALTER TABLE chat_messages ADD COLUMN IF NOT EXISTS admin_deleted_at timestamp(6);
ALTER TABLE chat_messages ADD COLUMN IF NOT EXISTS delete_broadcast_at timestamp(6);
