BEGIN;
CREATE TABLE IF NOT EXISTS push_bundles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    bundle_key VARCHAR(64) NOT NULL,
    last_alerted_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    last_alerted_ref BIGINT,
    names TEXT,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT ux_push_bundles_user_key UNIQUE (user_id, bundle_key)
);
COMMIT;
