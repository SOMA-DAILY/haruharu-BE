package org.son.haruharu.domain.ticket;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.testcontainers.containers.PostgreSQLContainer;
import org.testcontainers.junit.jupiter.Container;
import org.testcontainers.junit.jupiter.Testcontainers;

import java.nio.file.Files;
import java.nio.file.Path;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.util.ArrayList;
import java.util.List;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

/** 실제 배포 SQL(#492)을 구버전 코인 스키마가 있는 PostgreSQL에 적용해 코인 → 티켓 전환과 되돌리기를 검증한다. */
@Testcontainers
class TicketMigrationPostgresTest {
    @Container
    static final PostgreSQLContainer<?> POSTGRES = new PostgreSQLContainer<>("postgres:16-alpine");

    private Connection connection() throws SQLException {
        return DriverManager.getConnection(POSTGRES.getJdbcUrl(), POSTGRES.getUsername(), POSTGRES.getPassword());
    }

    /** 구버전 엔티티(CoinWallet·CoinLedger·IapProduct·IapPurchase)를 Hibernate 가 만들던 모양 그대로다. */
    @BeforeEach
    void legacySchema() throws Exception {
        try (var c = connection(); var s = c.createStatement()) {
            s.execute("""
                    DROP SCHEMA public CASCADE;
                    CREATE SCHEMA public;
                    CREATE TABLE coin_wallet (
                        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        created_at timestamp(6) NOT NULL, updated_at timestamp(6) NOT NULL, deleted_at timestamp(6),
                        user_id bigint NOT NULL UNIQUE, paid_balance bigint NOT NULL, reward_balance bigint NOT NULL);
                    CREATE TABLE coin_ledger (
                        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        user_id bigint NOT NULL, delta bigint NOT NULL, balance_after bigint NOT NULL,
                        bucket varchar(10) NOT NULL CHECK (bucket IN ('PAID', 'REWARD')),
                        reason varchar(40) NOT NULL CHECK (reason IN ('PURCHASE', 'MISSION_REWARD', 'MATCH_ENTER',
                            'MATCH_REFUND', 'CHAT_OPEN', 'REFUND_REVOKE', 'SIGNUP_BONUS', 'UPLOAD_COMPLETION_REWARD')),
                        ref_type varchar(40), ref_id varchar(40), created_at timestamp(6) NOT NULL);
                    CREATE INDEX idx_coin_ledger_user_created ON coin_ledger (user_id, created_at);
                    CREATE TABLE iap_product (
                        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        created_at timestamp(6) NOT NULL, updated_at timestamp(6) NOT NULL, deleted_at timestamp(6),
                        store_product_id varchar(100) NOT NULL UNIQUE, store varchar(20) NOT NULL,
                        coin_amount bigint NOT NULL, bonus_amount bigint DEFAULT 0 NOT NULL,
                        price integer NOT NULL, currency varchar(10) NOT NULL, active boolean NOT NULL);
                    CREATE TABLE iap_purchase (
                        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        created_at timestamp(6) NOT NULL, updated_at timestamp(6) NOT NULL, deleted_at timestamp(6),
                        user_id bigint NOT NULL, product_id bigint NOT NULL, store_product_id varchar(100) NOT NULL,
                        store_transaction_id varchar(100) NOT NULL UNIQUE, store varchar(20) NOT NULL,
                        coin_amount bigint NOT NULL, status varchar(20) NOT NULL,
                        purchased_at timestamp(6) NOT NULL, refunded_at timestamp(6));
                    -- 가입 시점에 만들어진 0 잔액 지갑 3개. 3번은 탈퇴로 soft-delete 된 지갑이다.
                    INSERT INTO coin_wallet (created_at, updated_at, user_id, paid_balance, reward_balance)
                        SELECT now(), now(), g, 0, 0 FROM generate_series(1, 3) g;
                    UPDATE coin_wallet SET deleted_at = now() WHERE user_id = 3;
                    """);
        }
    }

    private void script(Connection c, String phase) throws Exception {
        Path root = Path.of(System.getProperty("user.dir"));
        if (!Files.isDirectory(root.resolve("scripts/sql"))) root = root.getParent();
        try (var s = c.createStatement()) {
            s.execute(Files.readString(root.resolve("scripts/sql/492-ticket-" + phase + ".sql")));
        }
    }

    /** 스크립트가 예외로 멈추는지 확인하고, 그 스크립트가 열어 둔 트랜잭션을 닫는다. */
    private void failingScript(Connection c, String phase, String message) {
        assertThatThrownBy(() -> script(c, phase)).hasMessageContaining(message);
        try (var s = c.createStatement()) {
            s.execute("ROLLBACK");
        } catch (SQLException e) {
            throw new IllegalStateException(e);
        }
    }

    private List<String> columns(Connection c, String table) throws SQLException {
        List<String> names = new ArrayList<>();
        try (var s = c.prepareStatement("""
                SELECT column_name FROM information_schema.columns
                WHERE table_schema = 'public' AND table_name = ? ORDER BY ordinal_position""")) {
            s.setString(1, table);
            try (var rs = s.executeQuery()) {
                while (rs.next()) names.add(rs.getString(1));
            }
        }
        return names;
    }

    private long count(Connection c, String sql) throws SQLException {
        try (var s = c.createStatement(); var rs = s.executeQuery(sql)) {
            rs.next();
            return rs.getLong(1);
        }
    }

    @Test
    @DisplayName("코인 스키마를 티켓으로 옮기고 지갑 행을 보존하며, 되돌린 뒤 다시 적용할 수 있다")
    void givenLegacyCoinSchema_whenMigrateAndRollback_thenRoundTrips() throws Exception {
        try (var c = connection()) {
            script(c, "preflight");
            script(c, "up");
            script(c, "verify");

            assertThat(columns(c, "ticket_wallet"))
                    .containsExactlyInAnyOrder("id", "created_at", "updated_at", "deleted_at", "user_id", "balance");
            assertThat(columns(c, "ticket_ledger")).containsExactlyInAnyOrder(
                    "id", "user_id", "delta", "balance_after", "reason", "ref_type", "ref_id", "memo", "created_at");
            assertThat(columns(c, "iap_product")).contains("ticket_amount").doesNotContain("coin_amount", "bonus_amount");
            assertThat(columns(c, "iap_purchase")).contains("ticket_amount", "unrevoked_ticket_amount")
                    .doesNotContain("coin_amount");
            // 지갑은 soft-delete 된 것까지 그대로 따라온다 — 유니크 슬롯 점유 구조(#298)가 유지돼야 한다.
            assertThat(count(c, "SELECT count(*) FROM ticket_wallet")).isEqualTo(3);
            assertThat(count(c, "SELECT count(*) FROM ticket_wallet WHERE deleted_at IS NOT NULL")).isEqualTo(1);
            assertThat(count(c, "SELECT count(*) FROM pg_class WHERE relname LIKE '%coin%'")).isZero();

            // 새 사유는 받고, 폐기된 사유와 같은 유저의 두 번째 지갑은 DB 가 거절한다.
            try (var s = c.createStatement()) {
                s.execute("""
                        INSERT INTO ticket_ledger (user_id, delta, balance_after, reason, memo, created_at)
                        VALUES (1, 1, 1, 'ADMIN_GRANT', '보상', now())""");
                assertThatThrownBy(() -> s.execute("""
                        INSERT INTO ticket_ledger (user_id, delta, balance_after, reason, created_at)
                        VALUES (1, 20, 20, 'SIGNUP_BONUS', now())""")).hasMessageContaining("ticket_ledger_reason_check");
                assertThatThrownBy(() -> s.execute("""
                        INSERT INTO ticket_wallet (created_at, updated_at, user_id, balance)
                        VALUES (now(), now(), 3, 0)""")).hasMessageContaining("ticket_wallet_user_id_key");
            }

            // 새 버전이 원장을 쓴 뒤에는 코인 모델로 되돌릴 수 없다.
            failingScript(c, "down", "roll forward");
            try (var s = c.createStatement()) {
                s.execute("DELETE FROM ticket_ledger");
            }

            script(c, "down");
            assertThat(columns(c, "coin_wallet")).containsExactlyInAnyOrder(
                    "id", "created_at", "updated_at", "deleted_at", "user_id", "paid_balance", "reward_balance");
            assertThat(columns(c, "coin_ledger")).contains("bucket").doesNotContain("memo");
            assertThat(columns(c, "iap_product")).contains("coin_amount", "bonus_amount");
            assertThat(columns(c, "iap_purchase")).contains("coin_amount").doesNotContain("unrevoked_ticket_amount");
            assertThat(count(c, "SELECT count(*) FROM coin_wallet")).isEqualTo(3);
            assertThat(count(c, "SELECT count(*) FROM pg_class WHERE relname LIKE '%ticket%'")).isZero();

            script(c, "up");
            script(c, "verify");
        }
    }

    @Test
    @DisplayName("코인 잔액·원장·상품·구매가 남아 있으면 옮기지 않고 멈춘다")
    void givenLegacyCoinData_whenMigrate_thenBlocks() throws Exception {
        try (var c = connection(); var s = c.createStatement()) {
            s.execute("UPDATE coin_wallet SET reward_balance = 20 WHERE user_id = 1");
            failingScript(c, "up", "non-zero balances");
            s.execute("UPDATE coin_wallet SET reward_balance = 0");

            s.execute("""
                    INSERT INTO coin_ledger (user_id, delta, balance_after, bucket, reason, created_at)
                    VALUES (1, 20, 20, 'REWARD', 'SIGNUP_BONUS', now())""");
            failingScript(c, "up", "coin_ledger has rows");
            s.execute("DELETE FROM coin_ledger");

            s.execute("""
                    INSERT INTO iap_product (created_at, updated_at, store_product_id, store, coin_amount, price, currency, active)
                    VALUES (now(), now(), 'groom_60', 'APP_STORE', 60, 9800, 'KRW', true)""");
            failingScript(c, "up", "iap_product/iap_purchase have rows");

            // 막힌 뒤에도 코인 스키마는 그대로다.
            assertThat(columns(c, "coin_wallet")).contains("paid_balance", "reward_balance");
            assertThat(count(c, "SELECT count(*) FROM pg_class WHERE relname = 'ticket_wallet'")).isZero();
        }
    }

    @Test
    @DisplayName("새 버전이 먼저 떠서 빈 ticket_* 테이블이 생겼으면 옮기지 않고 멈춘다")
    void givenTicketTablesAlreadyCreated_whenMigrate_thenBlocks() throws Exception {
        try (var c = connection(); var s = c.createStatement()) {
            s.execute("CREATE TABLE ticket_wallet (id bigint PRIMARY KEY)");

            failingScript(c, "up", "ticket_* tables already exist");

            assertThat(count(c, "SELECT count(*) FROM coin_wallet")).isEqualTo(3);
        }
    }
}
