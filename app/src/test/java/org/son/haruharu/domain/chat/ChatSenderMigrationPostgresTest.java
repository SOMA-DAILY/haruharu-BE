package org.son.haruharu.domain.chat;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.testcontainers.containers.PostgreSQLContainer;
import org.testcontainers.junit.jupiter.Container;
import org.testcontainers.junit.jupiter.Testcontainers;

import java.nio.file.Files;
import java.nio.file.Path;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

/** 실제 배포 SQL을 구버전 제약/FK/답장/삭제/과거 미션 컬럼이 있는 PostgreSQL에 적용한다. */
@Testcontainers
class ChatSenderMigrationPostgresTest {
    @Container
    static final PostgreSQLContainer<?> POSTGRES = new PostgreSQLContainer<>("postgres:16-alpine");

    private Connection connection() throws SQLException {
        return DriverManager.getConnection(POSTGRES.getJdbcUrl(), POSTGRES.getUsername(), POSTGRES.getPassword());
    }

    @BeforeEach
    void legacySchema() throws Exception {
        try (var c = connection(); var s = c.createStatement()) {
            s.execute("""
                    DROP SCHEMA public CASCADE;
                    CREATE SCHEMA public;
                    CREATE TABLE users (id bigint PRIMARY KEY);
                    INSERT INTO users VALUES (1), (2);
                    CREATE TABLE chat_messages (
                        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        chat_room_id bigint NOT NULL,
                        sender_id bigint NOT NULL REFERENCES users(id),
                        content text NOT NULL,
                        message_type varchar(20) NOT NULL DEFAULT 'TEXT' CHECK (message_type IN ('TEXT', 'ADMIN')),
                        schedule_item_id bigint,
                        client_request_id varchar(36),
                        reply_to_message_id bigint REFERENCES chat_messages(id),
                        reply_preview_sender varchar(20), reply_preview_content varchar(50),
                        created_at timestamp NOT NULL DEFAULT now(),
                        admin_deleted_at timestamp, deleted_at timestamptz,
                        operator_mission_id bigint,
                        CONSTRAINT uq_chat_messages_reply_request UNIQUE (chat_room_id, sender_id, client_request_id)
                    );
                    CREATE TABLE chat_message_reactions (message_id bigint REFERENCES chat_messages(id), user_id bigint);
                    INSERT INTO chat_messages(chat_room_id, sender_id, content, message_type, schedule_item_id,
                        admin_deleted_at, operator_mission_id) VALUES (10, 1, '기존 공지', 'ADMIN', 100, now(), 77);
                    INSERT INTO chat_messages(chat_room_id, sender_id, content, reply_to_message_id,
                        reply_preview_sender, reply_preview_content) VALUES (10, 2, '답장', 1, '하루', '기존 공지');
                    INSERT INTO chat_messages(chat_room_id, sender_id, content, deleted_at)
                        VALUES (10, 1, '같은 계정의 일반 메시지', now());
                    INSERT INTO chat_message_reactions VALUES (1, 2);
                    """);
        }
    }

    private void script(Connection c, String phase) throws Exception {
        Path root = Path.of(System.getProperty("user.dir"));
        if (!Files.isDirectory(root.resolve("scripts/sql"))) root = root.getParent();
        try (var s = c.createStatement()) {
            s.execute(Files.readString(root.resolve("scripts/sql/484-chat-sender-" + phase + ".sql")));
        }
    }

    @Test
    @DisplayName("기존 ADMIN만 SYSTEM으로 이관하고 답장·반응·삭제·미션 참조를 보존한 뒤 롤백한다")
    void givenLegacyMessages_whenMigrateAndRollback_thenPreservesData() throws Exception {
        try (var c = connection(); var s = c.createStatement()) {
            script(c, "preflight");
            script(c, "up");
            script(c, "verify");
            try (var rows = s.executeQuery("select * from chat_messages order by id")) {
                assertThat(rows.next()).isTrue();
                assertThat(rows.getString("sender_type")).isEqualTo("SYSTEM");
                assertThat(rows.getObject("sender_id")).isNull();
                assertThat(rows.getString("message_type")).isEqualTo("TEXT");
                assertThat(rows.getString("content")).isEqualTo("기존 공지");
                assertThat(rows.getLong("schedule_item_id")).isEqualTo(100);
                assertThat(rows.getLong("operator_mission_id")).isEqualTo(77);
                assertThat(rows.getObject("admin_deleted_at")).isNotNull();
                assertThat(rows.next()).isTrue();
                assertThat(rows.getLong("reply_to_message_id")).isEqualTo(1);
                assertThat(rows.getString("reply_preview_sender")).isEqualTo("하루");
                assertThat(rows.next()).isTrue();
                assertThat(rows.getString("sender_type")).isEqualTo("USER");
                assertThat(rows.getLong("sender_id")).isEqualTo(1);
                assertThat(rows.getObject("deleted_at")).isNotNull();
            }
            try (var rows = s.executeQuery("select count(*) from chat_message_reactions where message_id=1")) {
                rows.next();
                assertThat(rows.getInt(1)).isEqualTo(1);
            }
            script(c, "down");
            try (var rows = s.executeQuery("select sender_id, message_type from chat_messages where id=1")) {
                rows.next();
                assertThat(rows.getLong(1)).isEqualTo(1);
                assertThat(rows.getString(2)).isEqualTo("ADMIN");
            }
        }
    }

    @Test
    @DisplayName("DB는 발신자 조합·NOT NULL·허용 타입·편성 중복을 강제하고 일반 유저 FK를 유지한다")
    void givenMigratedSchema_whenInsertInvalidRows_thenDbRejects() throws Exception {
        try (var c = connection(); var s = c.createStatement()) {
            script(c, "up");
            s.executeUpdate("insert into chat_messages(chat_room_id, sender_id, sender_type, content) values (10, 2, 'USER', '유저')");
            s.executeUpdate("insert into chat_messages(chat_room_id, sender_id, sender_type, content, schedule_item_id) values (10, null, 'SYSTEM', '새 공지', 200)");
            for (String values : new String[]{"null, 'USER'", "1, 'SYSTEM'", "1, null", "null, null", "null, 'UNKNOWN'", "999, 'USER'"}) {
                assertThatThrownBy(() -> s.executeUpdate("insert into chat_messages(chat_room_id, sender_id, sender_type, content) values (10, " + values + ", '거부')"))
                        .isInstanceOf(SQLException.class);
            }
            assertThatThrownBy(() -> s.executeUpdate("insert into chat_messages(chat_room_id, sender_type, content, schedule_item_id) values (10, 'SYSTEM', '중복', 200)"))
                    .isInstanceOf(SQLException.class).hasMessageContaining("uq_chat_messages_schedule_item");
            assertThatThrownBy(() -> script(c, "down"))
                    .isInstanceOf(SQLException.class).hasMessageContaining("New system messages exist");
            s.execute("ROLLBACK");
            try (var rows = s.executeQuery("select count(*) from chat_messages where sender_type='SYSTEM'")) {
                rows.next();
                assertThat(rows.getInt(1)).isEqualTo(2);
            }
        }
    }
}
